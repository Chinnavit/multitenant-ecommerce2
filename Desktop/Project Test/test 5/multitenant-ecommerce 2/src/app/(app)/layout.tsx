import type { Metadata } from "next";
import { DM_Sans } from "next/font/google";
import { NuqsAdapter } from "nuqs/adapters/next/app";
// 1. import ส่วนนี้เข้ามา
import { GoogleAnalytics } from '@next/third-parties/google'; 

import { TRPCReactProvider } from "@/trpc/client";
import { Toaster } from "@/components/ui/sonner";

import "./globals.css";

const dmSanas = DM_Sans ({
  subsets:["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

/**
 * Application root layout that wraps page content with app providers, global styles, and analytics.
 *
 * Renders an HTML document whose body applies the global font and antialiasing, wraps `children` with
 * NuqsAdapter and TRPCReactProvider, includes a Toaster for notifications, and mounts Google Analytics
 * with a configured measurement ID.
 *
 * @param children - Page content to render inside the NuqsAdapter and TRPCReactProvider; the Toaster is rendered alongside this content.
 * @returns The root HTML element for the application layout.
 */
export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <body
        className={`${dmSanas.className} antialiased`}
      >
        <NuqsAdapter>
        <TRPCReactProvider>
          {children}
          <Toaster/>
        </TRPCReactProvider>
        </NuqsAdapter>
        
        {/* 2. วาง Component ไว้ตรงนี้ (เปลี่ยน GA_MEASUREMENT_ID เป็น ID ของคุณ) */}
        <GoogleAnalytics gaId="G-6YG5QM4WK2" /> 
      </body>
    </html>
  );
}